"""App and menu-bar icons (spec §10.2 UI): writes art/icons/{app,tray}/scene.rml. Render with art/icons/render.sh.

Both are drawn white-on-dark where they need transparency; render.sh turns brightness into alpha, because
`rive --screenshot` always writes an opaque background.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "tools"))
from pet import eye  # noqa: E402
from rml import curve, ellipse, fill, path, rect, shape, solid, stroke, triangle  # noqa: E402

HERE = os.path.dirname(__file__)
WHITE = "FFFFFFFF"


def doc(name: str, size: int, children: str) -> str:
    return (
        '<Rive version="1" kind="fragment">\n'
        f'<!-- Generated by art/icons/make.py; edit that, not this. -->\n'
        f'<Artboard width="{size}" height="{size}" name="{name}" id="0:2"><LayoutComponentStyle name="Artboard Style" id="0:5"/>\n'
        f'{children}\n</Artboard>\n</Rive>\n'
    )


def node(name: str, children: str, x: float = 0, y: float = 0, scale: float = 1) -> str:
    return f'<Node x="{x:g}" y="{y:g}" scaleX="{scale:g}" scaleY="{scale:g}" name="{name}">{children}</Node>'


def paw(color: str) -> str:
    """A paw print centred on 0,0, about 100 wide."""
    toes = "".join(shape(f"Toe {i}", ellipse(22, 28), fill(solid(color)), x=x, y=y, rotation=r)
                   for i, (x, y, r) in enumerate([(-38, -10, -0.35), (-14, -36, -0.1), (14, -36, 0.1), (38, -10, 0.35)]))
    pad = shape("Pad", curve([(0, -4), (30, 8), (36, 34), (14, 46), (0, 40), (-14, 46), (-36, 34), (-30, 8)], closed=True), fill(solid(color)))
    return toes + pad


def write(name: str, rml: str) -> None:
    d = os.path.join(HERE, name)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "scene.rml"), "w") as f:
        f.write(rml)
    with open(os.path.join(d, "rive.yaml"), "w") as f:
        f.write(f"name: {name}\nlogs:\n  file: build/rive.log\n  problems: build/problems.log\n")


# menu bar: a template image (black + alpha once rendered), drawn large and scaled down by render.sh
write("tray", doc("Tray", 176, node("Paw", paw(WHITE), x=88, y=82, scale=1.45)))

# app icon: macOS grid, an 824 pt rounded square on a 1024 canvas; the mask project is its alpha
SQUARE = 824
GINGER, GINGER_DARK, LINE, CREAM = "FFE8A15C", "FFCB8240", "FF7A4520", "FFFBE3C6"
ear = lambda s: shape(f"Ear {s}", triangle(180, 190), fill(solid(GINGER)) + stroke(solid(LINE), 12), x=175 * s, y=-205, rotation=0.4 * s)  # noqa: E731
inner = lambda s: shape(f"Inner {s}", triangle(96, 104), fill(solid("FFF0B4B0")), x=175 * s, y=-196, rotation=0.4 * s)  # noqa: E731
face = node("Cat", (
    node("Eyes", eye(-1, 27) + eye(1, 27), y=-10, scale=3.8)
    + shape("Nose", triangle(44, 30), fill(solid("FFE79A9A")), y=60, rotation=3.1415927)
    + shape("Mouth", path([(-34, 96), (-16, 110), (0, 94), (16, 110), (34, 96)], radius=10), stroke(solid(LINE), 10))
    + shape("Muzzle", ellipse(230, 140), fill(solid(CREAM)), y=90)
    + shape("Head", ellipse(560, 450), fill(solid(GINGER)) + stroke(solid(LINE), 14))
    + inner(-1) + inner(1) + ear(-1) + ear(1)
), x=512, y=620)
bg = shape("Square", rect(SQUARE, SQUARE, 185), fill(solid("FF2F6F73")), x=512, y=512)
glow = shape("Glow", ellipse(700, 700), fill(solid("FF3C8A8F")), x=512, y=430)
paw_mark = node("Paw Mark", paw("FF5FA7AB"), x=780, y=250, scale=0.9)
write("app", doc("App", 1024, node("Clip", face + paw_mark + glow) + bg))
write("app-mask", doc("App Mask", 1024, shape("Square", rect(SQUARE, SQUARE, 185), fill(solid(WHITE)), x=512, y=512)))
print("wrote tray, app, app-mask")
